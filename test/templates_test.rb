require 'erb'
require 'fileutils'
require 'minitest/autorun'
require 'open3'
require 'tmpdir'

class TemplateContext
  def initialize(properties)
    @properties = properties
  end

  def p(name)
    @properties.fetch(name)
  end

  def if_p(name)
    yield @properties[name] if @properties.key?(name)
  end

  def get_binding
    binding
  end
end

class TemplatesTest < Minitest::Test
  ROOT = File.expand_path('..', __dir__)

  def setup
    @directory = Dir.mktmpdir
    @marker = File.join(@directory, 'unexpected-command')
    @bin = File.join(@directory, 'bin')
    FileUtils.mkdir_p(@bin)
    %w[sysctl resolvconf sleep date service].each do |command|
      File.write(File.join(@bin, command), "#!/bin/bash\nexit 0\n")
      FileUtils.chmod(0755, File.join(@bin, command))
    end
    if RUBY_PLATFORM.include?('darwin')
      File.write(File.join(@bin, 'sed'), "#!/bin/bash\nshift\nexec /usr/bin/sed -i '' \"$@\"\n")
      FileUtils.chmod(0755, File.join(@bin, 'sed'))
    end
  end

  def teardown
    FileUtils.remove_entry(@directory)
  end

  def render(job, properties, filename = 'pre-start.sh.erb')
    path = "jobs/#{job}/templates/#{filename}"
    source = if ENV['TEMPLATE_REF']
               output, status = Open3.capture2('git', '-C', ROOT, 'show', "#{ENV['TEMPLATE_REF']}:#{path}")
               raise 'Cannot read template' unless status.success?
               output
             else
               File.read(File.join(ROOT, path))
             end
    ERB.new(source).result(TemplateContext.new(properties).get_binding)
  end

  def execute(script)
    script = script.gsub('/etc/', "#{@directory}/etc/").gsub('/sbin/resolvconf', File.join(@bin, 'resolvconf'))
    _stdout, stderr, status = Open3.capture3({'PATH' => "#{@bin}:#{ENV.fetch('PATH')}"}, 'bash', stdin_data: script)
    assert status.success?, stderr
    refute File.exist?(@marker), 'Property text executed as a shell command'
    stderr
  end

  def test_login_banner_preserves_heredoc_markers_and_shell_syntax
    FileUtils.mkdir_p(File.join(@directory, 'etc'))
    text = "Welcome\nEOF\ntouch #{@marker}\n# $(touch #{@marker}) ' \" \\"
    execute(render('login_banner', {'login_banner.text' => text}))
    assert_equal text + "\n", File.read(File.join(@directory, 'etc/issue.net'))
  end

  def test_resolver_properties_are_literal_text
    tail = File.join(@directory, 'etc/resolvconf/resolv.conf.d/tail')
    FileUtils.mkdir_p(File.dirname(tail))
    File.write(tail, "search old\noptions old\n")
    search = "$(touch #{@marker}) example.org"
    option = "rotate\"; touch #{@marker}; #"
    execute(render('resolv', {'search' => search, 'options' => [option]}))
    assert_equal "search #{search}\noptions #{option}\n", File.read(tail)
  end

  def test_modprobe_passes_a_single_module_argument
    File.write(File.join(@bin, 'modprobe'), "#!/bin/bash\nprintf '%s\\0' \"$@\" > '#{@directory}/arguments'\n")
    FileUtils.chmod(0755, File.join(@bin, 'modprobe'))
    name = "module; touch #{@marker}; #"
    execute(render('modprobe', {'modules' => [name]}, 'pre-start.erb'))
    assert_equal ['--', name], File.binread(File.join(@directory, 'arguments')).split("\0")
  end

  def test_sysctl_content_is_literal_and_prefix_is_a_filename
    FileUtils.mkdir_p(File.join(@directory, 'etc/sysctl.d'))
    value = "custom.value=$(touch #{@marker})\nEOF\ntouch #{@marker}"
    execute(render('sysctl', {'sysctl_conf_prefix' => '71', 'sysctl' => [value]}))
    expected = "# Autogenerated by bosh os-conf-release sysctl. Do not edit.\n#{value}\n"
    assert_equal expected, File.read(File.join(@directory, 'etc/sysctl.d/71-bosh-os-conf-sysctl.conf'))
    ['../outside', "71\nother", "$(touch #{@marker})"].each do |prefix|
      assert_raises(RuntimeError) { render('sysctl', {'sysctl_conf_prefix' => prefix, 'sysctl' => []}) }
    end
  end

  def test_audit_rules_and_delay_are_shell_arguments
    rules_file = File.join(@directory, 'etc/audit/rules.d/audit.rules')
    FileUtils.mkdir_p(File.dirname(rules_file))
    File.write(rules_file, '')
    rule = "-w /tmp/example'\ntouch #{@marker}\n#"
    execute(render('auditd', {'rules' => [rule], 'pre_start_delay' => "0'; touch #{@marker}; #"}, 'pre-start'))
    assert_includes File.read(rules_file), rule
    assert_includes File.read(rules_file), '-e 2'
  end

  def test_nofile_values_must_be_whole_nonnegative_integers
    defaults = {'nofile.soft' => 16384, 'nofile.hard' => '60000'}
    assert_includes render('limits', defaults), '--nofile=16384:60000'
    defaults.keys.each do |key|
      ['1; touch ignored', "1\n2", '$(true)', -1, 1.5].each do |value|
        assert_raises(RuntimeError) { render('limits', defaults.merge(key => value)) }
      end
    end
  end

  def test_limits_not_recommended_systemd_nofile_is_literal_text
    File.write(File.join(@bin, 'cp'), "#!/bin/bash\nexit 0\n")
    FileUtils.chmod(0755, File.join(@bin, 'cp'))
    FileUtils.mkdir_p(File.join(@directory, 'etc/systemd'))
    value = "infinity\"; touch #{@marker}; # $(touch #{@marker})"
    execute(render('limits_not_recommended', {'limits_systemd_default_nofile' => value}))
    assert_equal "DefaultLimitNOFILE=#{value}\n", File.read(File.join(@directory, 'etc/systemd/system.conf'))
  end

  def test_tcp_keepalive_values_must_be_whole_nonnegative_integers
    defaults = {'tcp_keepalive.time' => 120, 'tcp_keepalive.interval' => 30, 'tcp_keepalive.probes' => 8}
    FileUtils.mkdir_p(File.join(@directory, 'etc/sysctl.d'))
    execute(render('tcp_keepalive', defaults))
    assert_includes File.read(File.join(@directory, 'etc/sysctl.d/70-bosh-tcp-keepalive.conf')), 'net.ipv4.tcp_keepalive_time=120'
    defaults.keys.each do |key|
      ['1; touch ignored', "1\n2", '$(true)', -1, 1.5].each do |value|
        assert_raises(RuntimeError) { render('tcp_keepalive', defaults.merge(key => value)) }
      end
    end
  end
  def user_add_stubs(fail_usermod = false)
    home = File.join(@directory, 'home/testuser')
    FileUtils.mkdir_p(home)
    FileUtils.mkdir_p(File.join(@directory, 'etc'))
    File.write(File.join(@directory, 'etc/group'), '')
    scripts = {
      'getent' => "printf '%s\\n' 'testuser:x:123:123::#{home}:/bin/bash'",
      'passwd' => "printf '%s\\n' \"$*\" >> '#{@directory}/password-actions'",
      'usermod' => fail_usermod ? 'exit 1' : 'exit 0',
      'chpasswd' => "cat > '#{@directory}/password-input'",
      'chown' => "printf '%s\\n' \"$*\" > '#{@directory}/chown'",
      'runuser' => "printf '%s\\n' \"$1 $2 $3\" > '#{@directory}/runuser'; shift 3; exec \"$@\""
    }
    scripts.each do |name, body|
      File.write(File.join(@bin, name), "#!/bin/bash\n#{body}\n")
      FileUtils.chmod(0755, File.join(@bin, name))
    end
    home
  end

  def test_user_add_treats_shell_key_and_hash_as_data_and_does_not_trace_hashes
    home = user_add_stubs
    key = "ssh-rsa key'; touch #{@marker}; #"
    hash = "$6$salt$hash'; touch #{@marker}; #"
    user = {'name' => 'testuser', 'sudo' => false, 'public_key' => key,
            'crypted_password' => hash, 'shell' => "/bin/bash; touch #{@marker}"}
    trace = execute("set -x\n" + render('user_add', {'persistent_homes' => false, 'users' => [user]}))
    assert_equal key + "\n", File.read(File.join(home, '.ssh/authorized_keys'))
    assert_equal "testuser:#{hash}\n", File.read(File.join(@directory, 'password-input'))
    refute_includes trace, hash
    assert_equal "-l -- testuser\n", File.read(File.join(@directory, 'password-actions'))
    assert_equal "-u testuser --\n", File.read(File.join(@directory, 'runuser'))
    assert_equal "-R -h -- testuser: /home/testuser\n", File.read(File.join(@directory, 'chown'))
  end

  def test_user_add_rejects_shell_syntax_in_user_names
    ['bad; true', "good\nbad", '-root', '../root'].each do |name|
      assert_raises(RuntimeError) do
        render('user_add', {'persistent_homes' => false, 'users' => [{'name' => name, 'public_key' => 'key'}]})
      end
    end
  end

  def test_user_add_failure_leaves_password_locked
    user_add_stubs(true)
    script = render('user_add', {'persistent_homes' => false,
                                'users' => [{'name' => 'testuser', 'crypted_password' => '$6$salt$hash'}]})
    _out, _err, status = Open3.capture3({'PATH' => "#{@bin}:#{ENV.fetch('PATH')}"}, 'bash', stdin_data: script)
    refute status.success?
    assert_equal "-l -- testuser\n", File.read(File.join(@directory, 'password-actions'))
    refute File.exist?(File.join(@directory, 'password-input'))
  end

end
